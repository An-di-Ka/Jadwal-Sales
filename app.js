// ==> Proses mengurutkan hari ==>
const indexHariIni = new Date().getDay(),
  hari = ["Minggu", "Senin", "Selasa", "Rabu", "Kamis", "Jumat", "Sabtu"],
  hariDiurutkan = [];
for (let i = indexHariIni; i < 7; i++) hariDiurutkan.push(hari[i]);
for (let i = 0; i < indexHariIni; i++) hariDiurutkan.push(hari[i]);

// ==> "2026-08-03" --> "03 Agustus 2026"
function formatTanggal(kalender) {
  const namaBulanIndonesia = [
      "Januari",
      "Februari",
      "Maret",
      "April",
      "Mei",
      "Juni",
      "Juli",
      "Agustus",
      "September",
      "Oktober",
      "November",
      "Desember",
    ],
    tanggal = String(kalender.getDate()).padStart(2, "0"),
    bulan = namaBulanIndonesia[kalender.getMonth()],
    tahun = kalender.getFullYear();
  return `${tanggal} ${bulan}`;
}

// ==> FUNGSI UTAMA
function renderJadwal(query = "") {
  appDiv.innerHTML = ``;
  let semuaHtml = "";
  const kataKunci = query.toLowerCase();
  let adaHasil = false;

  hariDiurutkan.forEach((hari) => {
    const dataDisaring = dataJadwal[hari].filter((sales) => {
      const kecocokanNamaSales = sales.nama.toLowerCase().includes(kataKunci);
      const kecocokanBarang = sales.barang.some((b) =>
        b.toLowerCase().includes(kataKunci),
      );
      return kecocokanNamaSales || kecocokanBarang;
    });

    if (dataDisaring.length === 0) return;

    adaHasil = true;
    let salesHtml = "";
    dataDisaring.forEach((sales) => {
      // =>
      // ==>  Membuat Logo Sales  ==>
      const logo = logoMap[sales.nama] || "📦";

      // =>  Membuat jadwal kunjungan
      const jadwalMulai = new Date(sales.mulai);
      jadwalMulai.setHours(0, 0, 0, 0);

      const frekuensiValid =
        Number(sales.frekuensi) > 0 ? Number(sales.frekuensi) : 1;

      while (jadwalMulai < hariIni) {
        jadwalMulai.setDate(jadwalMulai.getDate() + frekuensiValid * 7);
      }

      let jadwalMulaiHariIni = "";
      if (formatTanggal(jadwalMulai) == formatTanggal(hariIni)) {
        jadwalMulaiHariIni = "Hari Ini";
      } else {
        jadwalMulaiHariIni = formatTanggal(jadwalMulai);
      }

      const jadwalBesok = new Date(jadwalMulai);
      jadwalBesok.setDate(jadwalBesok.getDate() + frekuensiValid * 7);

      // Barang Html
      let barangDirurutkan = sales.barang.toSorted();
      let barangHTML = barangDirurutkan.map((b) => `<li>${b}</li>`).join("");
      const autoBuka = query.length > 0 ? "active" : "";

      // Memasukan hasil ke salesHtml
      salesHtml += `
      <div class="sales-container">
        <div class="sales-item  ${autoBuka}">
          <div class="sales-icon">${logo}</div>
          <div class="sales-info">
            <div class="sales-name">${sales.nama}</div>
            <div class="sales-frecuency">${sales.frekuensi} Minggu Sekali</div>
            <div class="sales-schedule">
              <span class="start">🕒 ${jadwalMulaiHariIni}</span> -
              <span class="end">${formatTanggal(jadwalBesok)}</span></div>
          </div>
          <span class="sales-arrow">▼</span>
        </div>
        <div class="item-list">
          <ul> ${barangHTML}</ul>
        </div>
      </div>
      `;
    });

    // ==>  Membuat Hari Pertama menjadi menonjol  ==>
    const hariPertama = hari === hariDiurutkan[0];
    const bedgeHARIINI = hariPertama
      ? `<span class="badge-today">Hari Ini</span>`
      : "";

    // ==>  Memasukan semua element ke App Div  ==>
    semuaHtml += `
    <div class="card-day">
      <div class="day-header ${hariPertama ? "today" : ""}">
        <span class="day">${hari}</span>
        ${bedgeHARIINI}
      </div>
      <div class="sales-list">${salesHtml}</div>
    </div>`;
  });

  if (adaHasil) {
    appDiv.innerHTML = semuaHtml;
  } else {
    appDiv.innerHTML = `
      <div class="empty-state">
        <div style="font-size: 2rem; margin-bottom: 10px;">🔍</div>
        <div>Tidak menemukan sales atau barang <b>"${query}"</b></div>
      </div>
    `;
  }
}

renderJadwal();

